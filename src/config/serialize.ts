import type { Catalog } from '../catalog';
import type { Artifact, DiffEntry, Settings, UnknownEntry } from './types';
import { diffEntries } from './diff';

// Pure: no argument is touched, and the same inputs always produce the same
// text. This is the only place the file layout is decided.

const GENERATOR_URL = 'https://orangepane.github.io/libbitcoin-bs-config-generator/';

const CONFIG_HINT = '# bs reads this only when passed: bs --config bs.cfg';
const STORE_HINT = '# The store is created on first run, or by adding --make to that command.';
const ALL_DEFAULTS = '# All values are at defaults. bs runs without a config file.';
const UNKNOWN_NOTE = '# Not in this catalog; kept as written.';

/** `key = value` for one stored element. An empty value stays `key =`. */
function unknownLine (key: string, value: string): string {
  return value === '' ? `${key} =` : `${key} = ${value}`;
}

/** A catalog description rendered as comment lines, each prefixed once. */
function commentBlock (comment: string): string[] {
  return comment
    .split('\n')
    .map((line) => (line === '' ? '#' : `# ${line}`));
}

/** One `[section]` block: header, then comments and lines per entry. */
function sectionBlock (section: string, entries: readonly DiffEntry[]): string[] {
  const lines = ['', `[${section}]`];
  for (const entry of entries) {
    if (entry.comment !== '') lines.push(...commentBlock(entry.comment));
    lines.push(...entry.lines);
  }
  return lines;
}

/** Unknown keys grouped by section, in the order the importer first saw them. */
function groupUnknown (unknown: readonly UnknownEntry[]): Array<[string, UnknownEntry[]]> {
  const groups = new Map<string, UnknownEntry[]>();
  for (const entry of unknown) {
    if (entry.values.length === 0) continue;
    const group = groups.get(entry.section);
    if (group === undefined) groups.set(entry.section, [entry]);
    else group.push(entry);
  }
  return [...groups.entries()];
}

function unknownBlocks (unknown: readonly UnknownEntry[]): string[] {
  const lines: string[] = [];
  for (const [section, entries] of groupUnknown(unknown)) {
    lines.push('', `[${section}]`, UNKNOWN_NOTE);
    for (const entry of entries) {
      for (const value of entry.values) lines.push(unknownLine(entry.key, value));
    }
  }
  return lines;
}

/**
 * The `bs.cfg` text for the current settings, plus the entries it was rendered
 * from. Unknown imported keys are kept after the catalog sections; their values
 * are already strings and are emitted as written.
 */
export function buildArtifact (
  settings: Settings,
  defaults: Settings,
  catalog: Catalog,
  unknown: UnknownEntry[] = [],
): Artifact {
  const entries = diffEntries(settings, defaults, catalog);

  const rawNetwork = settings.bitcoin?.network;
  const network = typeof rawNetwork === 'string' && rawNetwork !== '' ? rawNetwork : 'mainnet';

  const lines: string[] = [
    `# Generated by ${GENERATOR_URL}`,
    `# Targets ${catalog.meta.version}; verified against bs ${catalog.meta.verifiedAgainst.version} on ${catalog.meta.verifiedAgainst.date}.`,
    CONFIG_HINT,
    STORE_HINT,
  ];

  const bySection = new Map<string, DiffEntry[]>();
  for (const entry of entries) {
    const group = bySection.get(entry.section);
    if (group === undefined) bySection.set(entry.section, [entry]);
    else group.push(entry);
  }

  for (const section of Object.values(catalog.sections)) {
    const sectionEntries = bySection.get(section.key);
    if (sectionEntries !== undefined) lines.push(...sectionBlock(section.key, sectionEntries));
  }

  if (entries.length === 0) lines.push('', ALL_DEFAULTS);

  lines.push(...unknownBlocks(unknown));

  return {
    text: `${lines.join('\n')}\n`,
    entries,
    changedCount: entries.length,
    network,
  };
}
