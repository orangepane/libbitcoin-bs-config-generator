// Import fidelity: the parser is the only way a bs.cfg gets back into the tool.
// Empty is a state, bad values are reported rather than coerced, and a generated
// file re-exports byte for byte.
import { describe, expect, it } from 'vitest';

import catalogJson from '../../src/catalog.json';
import { validateCatalog } from '../../src/catalog.schema';
import { getDefaults, stripDefaults } from '../../src/config/defaults';
import { defaultsFor } from '../../src/config/networks';
import {
  MAX_IMPORT_BYTES,
  MAX_IMPORT_LINES,
  MAX_VALUE_LENGTH,
  parseConf,
} from '../../src/config/parse';
import type { Catalog } from '../../src/catalog.schema';
import type { Settings } from '../../src/config/types';

const catalog: Catalog = validateCatalog(catalogJson);
const defaults = getDefaults(catalog);

function copy<T> (value: T): T {
  return JSON.parse(JSON.stringify(value)) as T;
}

describe('parseConf: structure', () => {
  it('parses a minimal file over the defaults', () => {
    const result = parseConf('[bitcoin]\nnetwork = testnet3\n', defaults, catalog);

    expect(result.settings.bitcoin.network).toBe('testnet3');
    expect(result.errors).toEqual([]);
    expect(result.unknown).toEqual([]);
  });

  it('starts from the full default tree', () => {
    const result = parseConf('[bitcoin]\nnetwork = signet\n', defaults, catalog);

    expect(result.settings.node.maximum_height).toBe(0);
    expect(Object.keys(result.settings).sort()).toEqual(Object.keys(defaults).sort());
  });

  it('reads CRLF files and ignores blank lines and full-line comments', () => {
    const text = [
      '# Generated by hand.',
      '',
      '[bitcoin]',
      '   # the network',
      'network = testnet4',
      '',
      '  [node]  ',
      'maximum_height = 840000',
      '',
    ].join('\r\n');

    const result = parseConf(text, defaults, catalog);

    expect(result.errors).toEqual([]);
    expect(result.settings.bitcoin.network).toBe('testnet4');
    expect(result.settings.node.maximum_height).toBe(840000);
  });

  it('keeps a # inside a value, because comments are full lines only', () => {
    const result = parseConf('[folders]\nroot = /srv/bs#2\n', defaults, catalog);

    expect(result.settings.folders.root).toBe('/srv/bs#2');
    expect(result.errors).toEqual([]);
  });

  it('splits on the first = only', () => {
    const result = parseConf('[folders]\nroot = /srv/a=b\n', defaults, catalog);

    expect(result.settings.folders.root).toBe('/srv/a=b');
  });

  it('trims surrounding whitespace from keys and values', () => {
    const result = parseConf('[  log  ]\n   verbose   =   true   \n', defaults, catalog);

    expect(result.settings.log.verbose).toBe(true);
    expect(result.errors).toEqual([]);
  });
});

describe('parseConf: lists', () => {
  it('replaces a non-empty list default on the first occurrence', () => {
    const result = parseConf('[inbound]\nbind = 127.0.0.1:8333\n', defaults, catalog);

    // inbound.bind defaults to ["0.0.0.0:8333"]: appending would keep a line the
    // file does not contain.
    expect(result.settings.inbound.bind).toEqual(['127.0.0.1:8333']);
    expect(defaults.inbound.bind).toEqual(['0.0.0.0:8333']);
  });

  it('appends each repeated list line', () => {
    const result = parseConf(
      '[electrum]\nbind = 127.0.0.1:50001\nbind = [::1]:50001\nbind = 192.168.1.10:50001\n',
      defaults,
      catalog,
    );

    expect(result.settings.electrum.bind).toEqual([
      '127.0.0.1:50001',
      '[::1]:50001',
      '192.168.1.10:50001',
    ]);
    expect(result.errors).toEqual([]);
  });

  it('does not share an array with the defaults tree', () => {
    const result = parseConf('[inbound]\nbind = 127.0.0.1:8333\n', defaults, catalog);

    expect(result.settings.inbound.bind).not.toBe(defaults.inbound.bind);
  });

  it('reports an empty list line instead of treating it as "off"', () => {
    const result = parseConf('[electrum]\nbind =\n', defaults, catalog);

    expect(result.settings.electrum.bind).toEqual([]);
    expect(result.errors).toHaveLength(1);
    expect(result.errors[0]).toContain('[electrum] bind');
    expect(result.errors[0]).toContain('no value was given');
  });
});

describe('parseConf: value kinds', () => {
  it('reads booleans case-insensitively', () => {
    const upper = parseConf('[node]\nprovide_filters = TRUE\n', defaults, catalog);
    const lower = parseConf('[log]\nverbose = false\n', defaults, catalog);

    expect(upper.settings.node.provide_filters).toBe(true);
    expect(upper.errors).toEqual([]);
    expect(lower.settings.log.verbose).toBe(false);
  });

  it('rejects a boolean that is not true or false and keeps the default', () => {
    const result = parseConf('[node]\nprovide_filters = yes\n', defaults, catalog);

    expect(result.settings.node.provide_filters).toBe(false);
    expect(result.errors).toHaveLength(1);
    expect(result.errors[0]).toContain('[node] provide_filters');
    expect(result.errors[0]).toContain('"yes" is not true or false');
    expect(result.errors[0]).toContain('provide_filters stays at false');
  });

  it('reads integers and decimals as numbers', () => {
    const result = parseConf(
      '[node]\nmaximum_height = 800000\nallowed_deviation = 2.5\n',
      defaults,
      catalog,
    );

    expect(result.settings.node.maximum_height).toBe(800000);
    expect(result.settings.node.allowed_deviation).toBe(2.5);
    expect(result.errors).toEqual([]);
  });

  it('rejects a non-integer for an integer setting and keeps the default', () => {
    const result = parseConf('[node]\nmaximum_height = 12.5\n', defaults, catalog);

    expect(result.settings.node.maximum_height).toBe(0);
    expect(result.errors).toHaveLength(1);
    expect(result.errors[0]).toContain('[node] maximum_height');
    expect(result.errors[0]).toContain('whole number');
    expect(result.errors[0]).toContain('maximum_height stays at 0');
  });

  it('rejects a non-number for a decimal setting and keeps the default', () => {
    const result = parseConf('[node]\nallowed_deviation = often\n', defaults, catalog);

    expect(result.settings.node.allowed_deviation).toBe(1.5);
    expect(result.errors[0]).toContain('[node] allowed_deviation');
    expect(result.errors[0]).toContain('allowed_deviation stays at 1.5');
  });

  it('reads an enum value from the catalog list', () => {
    const result = parseConf('[bitcoin]\nnetwork = signet\n', defaults, catalog);

    expect(result.settings.bitcoin.network).toBe('signet');
    expect(result.errors).toEqual([]);
  });

  it('rejects an enum value outside the catalog list and keeps the default', () => {
    const result = parseConf('[bitcoin]\nnetwork = regnet\n', defaults, catalog);

    expect(result.settings.bitcoin.network).toBe('mainnet');
    expect(result.errors).toHaveLength(1);
    expect(result.errors[0]).toContain('[bitcoin] network');
    expect(result.errors[0]).toContain('"regnet" is not one of mainnet, testnet3');
    expect(result.errors[0]).toContain('network stays at mainnet');
  });

  it('keeps text and path values as written', () => {
    const result = parseConf(
      '[bitcoin]\nmilestone = abc:1\n[folders]\nroot = /var/lib/bs\n',
      defaults,
      catalog,
    );

    expect(result.settings.bitcoin.milestone).toBe('abc:1');
    expect(result.settings.folders.root).toBe('/var/lib/bs');
    expect(result.errors).toEqual([]);
  });
});

describe('parseConf: unknown keys', () => {
  it('keeps unknown sections and keys out of settings, with every line', () => {
    const text = [
      '[node]',
      'brand_new_setting = 1',
      '[future_section]',
      'thing = a',
      'thing = b',
      'other = c',
    ].join('\n');

    const result = parseConf(text, defaults, catalog);

    expect(result.errors).toEqual([]);
    expect(result.settings.future_section).toBeUndefined();
    expect(result.settings.node.brand_new_setting).toBeUndefined();
    expect(result.unknown).toEqual([
      { section: 'node', key: 'brand_new_setting', values: ['1'] },
      { section: 'future_section', key: 'thing', values: ['a', 'b'] },
      { section: 'future_section', key: 'other', values: ['c'] },
    ]);
  });

  it('keeps an unknown key even when it looks like a known one in another section', () => {
    const result = parseConf('[peer]\nprovide_filters = true\n', defaults, catalog);

    expect(result.settings.peer.provide_filters).toBeUndefined();
    expect(result.unknown).toEqual([
      { section: 'peer', key: 'provide_filters', values: ['true'] },
    ]);
  });
});

describe('parseConf: duplicates', () => {
  it('takes the last scalar value and names both lines', () => {
    const result = parseConf(
      '[bitcoin]\nnetwork = testnet3\nnetwork = signet\n',
      defaults,
      catalog,
    );

    expect(result.settings.bitcoin.network).toBe('signet');
    expect(result.errors).toHaveLength(1);
    expect(result.errors[0]).toContain('[bitcoin] network');
    expect(result.errors[0]).toContain('also appears on line 2');
    expect(result.errors[0]).toContain('value from line 3 was used');
  });

  it('does not call repeated list lines duplicates', () => {
    const result = parseConf(
      '[electrum]\nbind = 127.0.0.1:50001\nbind = 127.0.0.1:50002\n',
      defaults,
      catalog,
    );

    expect(result.errors).toEqual([]);
  });
});

describe('parseConf: never throws', () => {
  it('reports structural noise and keeps the defaults', () => {
    const before = copy(defaults);
    const text = [
      '\uFEFFnoise before any header',
      '[]',
      '= 5',
      '[something',
      '[bitcoin]',
      'network =',
      '[node]',
      'maximum_height',
      'maximum_height =',
    ].join('\n');

    let result: ReturnType<typeof parseConf> | undefined;
    expect(() => { result = parseConf(text, defaults, catalog); }).not.toThrow();

    expect(result?.settings.bitcoin.network).toBe('mainnet');
    expect(result?.settings.node.maximum_height).toBe(0);
    expect(result?.errors.length).toBeGreaterThanOrEqual(5);
    expect(defaults).toEqual(before);
  });

  it('returns a full default tree for an empty file', () => {
    const result = parseConf('', defaults, catalog);

    expect(result.settings).toEqual(defaults);
    expect(result.errors).toEqual([]);
    expect(result.unknown).toEqual([]);
  });

  it('does not mutate the frozen defaults it is given', () => {
    const before = copy(defaults);
    const result = parseConf(
      '[node]\nprovide_filters = true\n[inbound]\nbind = 192.168.1.10:8333\nbind = 192.168.1.11:8333\n',
      defaults,
      catalog,
    );

    // A write to the frozen tree would have thrown; assert the tree anyway.
    expect(defaults).toEqual(before);
    expect(result.settings.inbound.bind).toHaveLength(2);
    expect(defaults.inbound.bind).toEqual(['0.0.0.0:8333']);
  });
});

describe('parseConf: round trip', () => {
  it('recovers the sparse config a generated file was built from', () => {
    // Written the way buildArtifact lays a file out: header block, [section]
    // headers, one comment above each entry, list keys repeated per element.
    const text = [
      '# bs.cfg generated by libbitcoin-bs-config-generator',
      '# https://orangepane.github.io/libbitcoin-bs-config-generator/',
      '# Reference: https://libbitcoin.org/',
      '#',
      '# Start with: bs --config bs.cfg',
      '',
      '[bitcoin]',
      '# Test Network 3',
      'network = testnet3',
      '',
      '[electrum]',
      '# The Electrum protocol server.',
      'bind = 127.0.0.1:50001',
      'bind = [::1]:50001',
      '',
      '[node]',
      '# Serve client filters to network connections.',
      'provide_filters = true',
      '# Maximum block height to populate (unlimited).',
      'maximum_height = 800000',
      '',
      '[table.filter_bk]',
      '# The number of buckets in the filter_bk table head (0 disables).',
      'buckets = 140000',
      '',
      '[log]',
      '# Verbose logging.',
      'verbose = true',
      '',
    ].join('\n');

    const result = parseConf(text, defaults, catalog);
    // The file names testnet3, so its tree sits on that network's defaults.
    const sparse: Settings = stripDefaults(result.settings, defaultsFor(catalog, 'testnet3'));

    expect(result.errors).toEqual([]);
    expect(result.unknown).toEqual([]);
    // The network line is part of the baseline now, so it is not "sparse".
    expect(result.settings.bitcoin.network).toBe('testnet3');
    expect(sparse).toEqual({
      electrum: { bind: ['127.0.0.1:50001', '[::1]:50001'] },
      node: { provide_filters: true, maximum_height: 800000 },
      'table.filter_bk': { buckets: 140000 },
      log: { verbose: true },
    });
  });
});

describe('parseConf: import limits', () => {
  it('refuses an oversized file without parsing it', () => {
    const text = '[log]\nverbose = true\n' + '#'.repeat(MAX_IMPORT_BYTES);
    const result = parseConf(text, defaults, catalog);

    expect(result.settings).toEqual(defaults);
    expect(result.errors).toHaveLength(1);
    expect(result.errors[0]).toContain('import limit');
    expect(result.settings.log.verbose).toBe(false);
  });

  it('refuses a file with too many lines', () => {
    const text = Array.from({ length: MAX_IMPORT_LINES + 1 }, () => '#').join('\n');
    const result = parseConf(text, defaults, catalog);

    expect(result.settings).toEqual(defaults);
    expect(result.errors[0]).toContain('line import limit');
  });

  it('ignores a value over the length limit and keeps the default', () => {
    const text = `[electrum]\nbanner_message = ${'x'.repeat(MAX_VALUE_LENGTH + 1)}\n`;
    const result = parseConf(text, defaults, catalog);

    expect(result.settings.electrum.banner_message).toBe(defaults.electrum.banner_message);
    expect(result.errors).toHaveLength(1);
    expect(result.errors[0]).toContain('character limit');
  });
});

describe('parseConf: the network in the file', () => {
  it('imports a testnet file onto that network, not onto mainnet', () => {
    // Importing while mainnet is selected must not drag mainnet chain
    // parameters into a testnet4 draft.
    const text = '[bitcoin]\nnetwork = testnet4\n\n[electrum]\nbind = 127.0.0.1\n';
    const result = parseConf(text, defaults, catalog);

    expect(result.settings.bitcoin.network).toBe('testnet4');
    expect(result.settings.bitcoin.bip16_activation_time)
      .toBe(defaultsFor(catalog, 'testnet4').bitcoin.bip16_activation_time);
    expect(result.settings.bitcoin.bip16_activation_time)
      .not.toBe(defaults.bitcoin.bip16_activation_time);
  });

  it('leaves the current network when the file names none', () => {
    const regtest = defaultsFor(catalog, 'regtest');
    const result = parseConf('[electrum]\nbind = 127.0.0.1\n', regtest, catalog);

    expect(result.settings.bitcoin.network).toBe('regtest');
  });
});
