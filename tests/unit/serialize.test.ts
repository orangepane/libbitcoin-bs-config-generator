// The serializer owns the file layout. Golden files pin the whole text so a
// change in spacing, comments or ordering is visible in the diff.
import { describe, expect, it } from 'vitest';

import catalogJson from '../../src/catalog.json';
import { validateCatalog } from '../../src/catalog.schema';
import type { Catalog } from '../../src/catalog.schema';
import { getDefaults, mixDefaults } from '../../src/config/defaults';
import { diffEntries } from '../../src/config/diff';
import { applyPreset, presetById } from '../../src/config/presets';
import { buildArtifact } from '../../src/config/serialize';
import type { Settings, UnknownEntry } from '../../src/config/types';

const catalog: Catalog = validateCatalog(catalogJson);
const defaults = getDefaults(catalog);

const goldens = import.meta.glob('./golden/*.cfg', { eager: true, query: '?raw', import: 'default' }) as Record<
  string,
  string
>;

function golden (name: string): string {
  const text = goldens[`./golden/${name}`];
  if (text === undefined) throw new Error(`missing golden file: ${name}`);
  return text;
}

function settingsWith (sparse: Settings): Settings {
  return mixDefaults(defaults, sparse);
}

/** A two-section catalog for cases the generated catalog cannot produce yet. */
function syntheticCatalog (): Catalog {
  return validateCatalog({
    meta: {
      project: 'test',
      version: 'v4',
      referenceUrl: 'https://example.org/reference.html',
      snapshot: '2026-11-06',
      verifiedAgainst: { version: '4.0.0', date: '2026-11-08', serverCommit: 'abc1234' },
      defaultsScope: 'network',
      generatedBy: 'tests',
      seedSha256: 'test',
      sectionCount: 2,
      settingCount: 3,
    },
    sections: {
      alpha: {
        key: 'alpha',
        title: 'Alpha',
        summary: 'Alpha settings.',
        tier: 'essential',
        settings: {
          note: {
            key: 'note',
            label: 'Note',
            help: 'First line.\nSecond line.',
            tier: 'essential',
            kind: 'text',
            default: 'x',
            emit: 'whenChanged',
          },
          word: {
            key: 'word',
            label: 'Word',
            help: 'The word is {}.',
            tier: 'advanced',
            kind: 'text',
            default: 'none',
            emit: 'whenChanged',
          },
        },
      },
      beta: {
        key: 'beta',
        title: 'Beta',
        summary: 'Beta settings.',
        tier: 'advanced',
        settings: {
          flag: {
            key: 'flag',
            label: 'Flag',
            help: 'Turn the flag on.',
            tier: 'advanced',
            kind: 'boolean',
            default: false,
            emit: 'whenChanged',
          },
        },
      },
    },
  });
}

describe('buildArtifact text', () => {
  it('writes only the header when every value is at its default', () => {
    expect(buildArtifact(defaults, defaults, catalog).text).toBe(golden('defaults.cfg'));
  });

  it('writes a preset over the defaults', () => {
    const preset = presetById('wallet-server');
    expect(preset).toBeDefined();
    if (preset === undefined) return;
    const settings = applyPreset(defaults, preset);
    expect(buildArtifact(settings, defaults, catalog).text).toBe(golden('wallet-server.cfg'));
  });

  it('writes a non-mainnet network and changed values', () => {
    const settings = settingsWith({
      bitcoin: { network: 'testnet4' },
      node: { maximum_height: 840000 },
      outbound: { seed: ['seed.one:48333', 'seed.two:48333'] },
    });
    expect(buildArtifact(settings, defaults, catalog).text).toBe(golden('testnet4.cfg'));
  });

  it('keeps imported keys the catalog does not know, under their own header', () => {
    const settings = settingsWith({ bitcoin: { network: 'signet' } });
    const unknown: UnknownEntry[] = [
      { section: 'future', key: 'mode', values: ['fast'] },
      { section: 'future', key: 'threshold', values: ['10', '20'] },
      { section: 'legacy', key: 'flag', values: ['true'] },
    ];
    expect(buildArtifact(settings, defaults, catalog, unknown).text).toBe(golden('unknown.cfg'));
  });

  it('prefixes every line of a multi-line comment', () => {
    const small = syntheticCatalog();
    const smallDefaults = getDefaults(small);
    const settings = mixDefaults(smallDefaults, {
      alpha: { note: 'y', word: 'hello' },
      beta: { flag: true },
    });

    expect(buildArtifact(settings, smallDefaults, small).text).toBe(
      [
        '# Generated by https://orangepane.github.io/libbitcoin-bs-config-generator/',
        '# Targets v4; verified against bs 4.0.0.',
        '# bs reads this only when passed: bs --config bs.cfg',
        '# The store is created on first run, or by adding --make to that command.',
        '',
        '[alpha]',
        '# First line.',
        '# Second line.',
        'note = y',
        '# The word is hello.',
        'word = hello',
        '',
        '[beta]',
        '# Turn the flag on.',
        'flag = true',
        '',
      ].join('\n'),
    );
  });

  it('separates sections with exactly one blank line and ends in one newline', () => {
    const text = buildArtifact(
      settingsWith({ bitcoin: { network: 'signet' }, outbound: { connections: 8 } }),
      defaults,
      catalog,
    ).text;

    expect(text.endsWith('\n')).toBe(true);
    expect(text.endsWith('\n\n')).toBe(false);
    expect(text).not.toContain('\n\n\n');
  });

  it('has no local paths or file URLs in the generated text', () => {
    const settings = settingsWith({ bitcoin: { network: 'regtest' }, outbound: { connections: 8 } });
    const text = buildArtifact(settings, defaults, catalog).text;

    expect(text).not.toContain('file://');
    expect(text).not.toMatch(/(^|\s)\/(Users|home|var|tmp|private)\//);
    expect(text).not.toContain('\\');
  });

  it('omits unknown sections whose values are empty', () => {
    const text = buildArtifact(defaults, defaults, catalog, [
      { section: 'future', key: 'mode', values: [] },
    ]).text;
    expect(text).not.toContain('[future]');
    expect(text.trimEnd().endsWith('config file.')).toBe(true);
  });

  it('reports the defaults notice even when only unknown keys are present', () => {
    const text = buildArtifact(defaults, defaults, catalog, [
      { section: 'future', key: 'mode', values: ['fast'] },
    ]).text;

    expect(text).toContain('# All values are at defaults. bs runs without a config file.');
    expect(text.indexOf('# All values are at defaults.')).toBeLessThan(text.indexOf('[future]'));
    expect(text).toContain('[future]\n# Not in this catalog; kept as written.\nmode = fast\n');
  });
});

describe('buildArtifact metadata', () => {
  it('derives entries and the changed count from the diff', () => {
    const settings = settingsWith({
      bitcoin: { network: 'testnet4' },
      outbound: { connections: 8 },
    });
    const artifact = buildArtifact(settings, defaults, catalog);

    expect(artifact.entries).toEqual(diffEntries(settings, defaults, catalog));
    expect(artifact.changedCount).toBe(artifact.entries.length);
    expect(artifact.changedCount).toBe(2);
  });

  it('reports mainnet when the network is absent or unreadable', () => {
    expect(buildArtifact(defaults, defaults, catalog).network).toBe('mainnet');
    expect(buildArtifact({}, defaults, catalog).network).toBe('mainnet');
    const broken = { bitcoin: { network: ['mainnet'] } } as unknown as Settings;
    expect(buildArtifact(broken, defaults, catalog).network).toBe('mainnet');
    expect(buildArtifact(broken, defaults, catalog).text).not.toContain('bs -n');
  });

  it('reports the selected network', () => {
    const artifact = buildArtifact(settingsWith({ bitcoin: { network: 'signet' } }), defaults, catalog);
    expect(artifact.network).toBe('signet');
  });

  it('does not mutate its arguments, including the unknown entries', () => {
    const settings = settingsWith({
      bitcoin: { network: 'signet' },
      outbound: { seed: ['seed.one:38333'] },
    });
    const unknown: UnknownEntry[] = [
      { section: 'future', key: 'mode', values: ['fast', 'slow'] },
    ];
    const before = [JSON.stringify(settings), JSON.stringify(defaults), JSON.stringify(catalog), JSON.stringify(unknown)];

    buildArtifact(settings, defaults, catalog, unknown);

    expect([
      JSON.stringify(settings),
      JSON.stringify(defaults),
      JSON.stringify(catalog),
      JSON.stringify(unknown),
    ]).toEqual(before);
  });
});

describe('buildArtifact provenance', () => {
  it('says which build the file was verified against', () => {
    const text = buildArtifact(mixDefaults(defaults, {}), defaults, catalog).text;
    const { version, date } = catalog.meta.verifiedAgainst;

    expect(text).toContain(`# Targets v4; verified against bs ${version}.`);
    // The date is our record, not the file's claim: a rendered date goes stale
    // while a version stays comparable to the reader's own bs.
    expect(text).not.toContain(date);
  });
});
